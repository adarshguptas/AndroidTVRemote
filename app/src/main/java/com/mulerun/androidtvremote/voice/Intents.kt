package com.mulerun.androidtvremote.voice

sealed class RemoteIntent {
    object PowerToggle : RemoteIntent()
    object PowerOff : RemoteIntent()
    object PowerOn : RemoteIntent()
    object VolumeUp : RemoteIntent()
    object VolumeDown : RemoteIntent()
    object Mute : RemoteIntent()
    data class VolumeSet(val percent: Int) : RemoteIntent()
    object Home : RemoteIntent()
    object Back : RemoteIntent()
    object Up : RemoteIntent()
    object Down : RemoteIntent()
    object Left : RemoteIntent()
    object Right : RemoteIntent()
    object Ok : RemoteIntent()
    object PlayPause : RemoteIntent()
    object Next : RemoteIntent()
    object Previous : RemoteIntent()
    object Stop : RemoteIntent()
    object Rewind : RemoteIntent()
    object FastForward : RemoteIntent()
    object ChannelUp : RemoteIntent()
    object ChannelDown : RemoteIntent()
    data class LaunchApp(val name: String, val uri: String) : RemoteIntent()
    data class TypeText(val text: String) : RemoteIntent()
    object Assistant : RemoteIntent()
    data class Unknown(val transcript: String) : RemoteIntent()
}
